const cache = new Map<string, Intl.DisplayNames | null>();

function displayNames(locale: string): Intl.DisplayNames | null {
  if (!cache.has(locale)) {
    try {
      cache.set(locale, new Intl.DisplayNames([locale, "ru"], { type: "region" }));
    } catch {
      cache.set(locale, null);
    }
  }
  return cache.get(locale) ?? null;
}

/** «KZ» → «Казахстан» на языке интерфейса; неизвестный код возвращается как есть. */
export function countryName(code: string | null | undefined, locale: string): string {
  if (!code) return "";
  const upper = code.toUpperCase();
  if (locale === "kk" && KK_COUNTRY_NAMES[upper]) return KK_COUNTRY_NAMES[upper];
  try {
    return displayNames(locale)?.of(upper) ?? upper;
  } catch {
    return upper;
  }
}

/** Варианты для выпадающего списка, отсортированные по названию. */
export function countryOptions(locale: string): { code: string; name: string }[] {
  const collator = new Intl.Collator(locale);
  return COUNTRY_CODES.map((code) => ({ code, name: countryName(code, locale) })).sort((a, b) =>
    collator.compare(a.name, b.name),
  );
}
